"""Batched damped Newton/Levenberg-Marquardt solver with recursive @jax.custom_jvp
implicit differentiation and dimensionless two-sided SVD rank checking."""

from __future__ import annotations

from typing import Callable

import jax
import jax.numpy as jnp
from jax import Array


class UnderConstrainedMechanismError(ValueError):
    """Raised when the dimensionless constraint Jacobian has column rank < 6 * N_movable."""


class RedundantMateError(ValueError):
    """Raised when the constraint system has more scalar constraints than Jacobian rank."""


def check_kinematic_determinacy(
    residual_fn: Callable[[Array, Array], Array],
    q0: Array,
    z0: Array,
    l_char: float = 100.0,
    svd_tol: float = 1e-8,
) -> tuple[int, Array]:
    """Verify two-sided kinematic determinacy via dimensionless SVD at nominal (q0, z0).

    Scales rotational columns of J_q by 1 / l_char and translational rows by 1 / l_char
    so that radians and millimeters are compared on a dimensionless footing.
    """
    J_q = jax.jacfwd(residual_fn, argnums=0)(q0, z0)
    n_constraints, n_dofs = J_q.shape
    n_movable = n_dofs // 6

    # Build column scaling: rotational DOFs [0,1,2] scaled by 1/l_char, translational [3,4,5] by 1.0
    col_scale_part = jnp.array(
        [1.0 / l_char, 1.0 / l_char, 1.0 / l_char, 1.0, 1.0, 1.0],
        dtype=J_q.dtype,
    )
    col_scale = jnp.tile(col_scale_part, n_movable)
    J_scaled = J_q * col_scale[None, :]

    svals = jnp.linalg.svd(J_scaled, compute_uv=False)
    s_max = jnp.maximum(svals[0], 1e-15)
    rank = int(jnp.sum(svals > svd_tol * s_max))

    if rank < n_dofs:
        _, _, vt = jnp.linalg.svd(J_scaled, full_matrices=True)
        null_vec = vt[-1]
        raise UnderConstrainedMechanismError(
            f"Assembly is under-constrained: rank(J_q) = {rank} < {n_dofs} active DOFs. "
            f"Unconstrained nullspace mode: {null_vec.tolist()}"
        )
    if n_constraints > rank:
        raise RedundantMateError(
            f"Assembly has redundant rigid constraints: C = {n_constraints} > rank(J_q) = {rank}. "
            "Use a kinematically determinate locating scheme (e.g., plane + parallel_pin_hole + "
            "clocking_pin_slot) or move secondary fasteners to jam_checks."
        )
    return rank, svals


def make_equilibrium_solver(
    residual_fn: Callable[[Array, Array], Array],
    n_dofs: int,
    num_iters: int = 5,
    damping_fp64: float = 1e-14,
    damping_fp32: float = 1e-7,
) -> Callable[[Array], Array]:
    """Create a differentiable equilibrium solver q*(z) satisfying F(q*(z), z) = 0.

    Uses a recursive @jax.custom_jvp rule:
      - Forward pass runs `num_iters` steps of damped Levenberg-Marquardt via `jax.lax.fori_loop`.
      - Tangent (JVP) rule recursively calls `solve_equilibrium(z)` as its primal evaluation
        and solves the linear implicit system at the equilibrium root.
      - Reverse (VJP) rule is automatically generated by JAX via linear transposition.
      - Second-order Hessians (`jax.hessian` = `jacfwd(jacrev)`) differentiate through the
        recursive JVP rule cleanly without ever unrolling the forward `fori_loop`.
    """

    def _lm_forward(z: Array) -> Array:
        dtype = z.dtype
        lam = damping_fp64 if dtype == jnp.float64 else damping_fp32
        q_init = jnp.zeros((n_dofs,), dtype=dtype)
        eye = jnp.eye(n_dofs, dtype=dtype)

        def body_fn(_: int, q: Array) -> Array:
            f_val = residual_fn(q, z)
            J_q = jax.jacfwd(residual_fn, argnums=0)(q, z)
            # For square full-rank determinate systems (C == n_dofs) with tiny damping:
            JT = jnp.swapaxes(J_q, -1, -2)
            H_lm = jnp.matmul(JT, J_q) + lam * eye
            rhs = -jnp.matmul(JT, f_val)
            dq = jnp.linalg.solve(H_lm, rhs)
            return q + dq

        return jax.lax.fori_loop(0, num_iters, body_fn, q_init)

    @jax.custom_jvp
    def solve_equilibrium(z: Array) -> Array:
        return _lm_forward(z)

    @solve_equilibrium.defjvp
    def _solve_equilibrium_jvp(
        primals: tuple[Array], tangents: tuple[Array]
    ) -> tuple[Array, Array]:
        (z,) = primals
        (z_dot,) = tangents

        # Recursive call to the @jax.custom_jvp primitive so higher-order derivatives
        # (such as jax.hessian = jacfwd(jacrev(...))) re-enter this exact implicit rule!
        q_star = solve_equilibrium(z)

        J_q = jax.jacfwd(residual_fn, argnums=0)(q_star, z)
        _, f_dot_z = jax.jvp(lambda z_var: residual_fn(q_star, z_var), (z,), (z_dot,))

        dtype = z.dtype
        n_c, n_q = J_q.shape
        if n_c == n_q:
            q_dot = jnp.linalg.solve(J_q, -f_dot_z)
        else:
            lam = damping_fp64 if dtype == jnp.float64 else damping_fp32
            JT = jnp.swapaxes(J_q, -1, -2)
            H_lm = jnp.matmul(JT, J_q) + lam * jnp.eye(n_q, dtype=dtype)
            q_dot = jnp.linalg.solve(H_lm, -jnp.matmul(JT, f_dot_z))

        return q_star, q_dot

    return solve_equilibrium
